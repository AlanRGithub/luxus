//! Fast, zero-dependency, single-pass streaming cryptographic hashers
//! (MD5, SHA-1, SHA-256, SHA-512) for Luxus checksum verification.

use std::fs::File;
use std::io::{BufReader, Read};
use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;

#[derive(Clone, Debug, Default)]
pub struct ChecksumResult {
    pub md5: String,
    pub sha1: String,
    pub sha256: String,
    pub sha512: String,
    pub bytes_hashed: u64,
    pub elapsed_secs: f64,
}

fn to_hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for &b in bytes {
        out.push(HEX[(b >> 4) as usize] as char);
        out.push(HEX[(b & 0x0f) as usize] as char);
    }
    out
}

/// Computes MD5, SHA-1, SHA-256, and SHA-512 in a single sequential 1 MiB buffered read.
pub fn compute_file_checksums<F>(
    path: &Path,
    cancel: &Arc<AtomicBool>,
    mut on_progress: F,
) -> Result<ChecksumResult, String>
where
    F: FnMut(f32),
{
    let start = std::time::Instant::now();
    let f = File::open(path).map_err(|e| format!("Cannot open file: {}", e))?;
    let total = f.metadata().map(|m| m.len()).unwrap_or(0).max(1);
    let mut reader = BufReader::with_capacity(1024 * 1024, f);

    let mut md5 = Md5::new();
    let mut sha1 = Sha1::new();
    let mut sha256 = Sha256::new();
    let mut sha512 = Sha512::new();

    let mut buf = vec![0u8; 1024 * 1024];
    let mut done: u64 = 0;

    loop {
        if cancel.load(Ordering::Relaxed) {
            return Err("Cancelled".into());
        }
        let n = reader
            .read(&mut buf)
            .map_err(|e| format!("Read error: {}", e))?;
        if n == 0 {
            break;
        }
        let slice = &buf[..n];
        md5.update(slice);
        sha1.update(slice);
        sha256.update(slice);
        sha512.update(slice);
        done += n as u64;
        on_progress((done as f64 / total as f64).clamp(0.0, 1.0) as f32);
    }

    Ok(ChecksumResult {
        md5: to_hex(&md5.finalize()),
        sha1: to_hex(&sha1.finalize()),
        sha256: to_hex(&sha256.finalize()),
        sha512: to_hex(&sha512.finalize()),
        bytes_hashed: done,
        elapsed_secs: start.elapsed().as_secs_f64(),
    })
}

