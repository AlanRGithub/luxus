pub fn tr(lang: Lang) -> &'static Strings {
    match lang {
        Lang::Es => &ES,
        Lang::En => &EN,
        Lang::Pt => &PT,
        Lang::Fr => &FR,
        Lang::De => &DE,
        Lang::It => &IT,
        Lang::Nl => &NL,
        Lang::Pl => &PL,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_locale_parsing() {
        assert_eq!(Lang::from_locale("es_MX.UTF-8"), Some(Lang::Es));
        assert_eq!(Lang::from_locale("en_US.UTF-8"), Some(Lang::En));
        assert_eq!(Lang::from_locale("pt_BR.UTF-8"), Some(Lang::Pt));
        assert_eq!(Lang::from_locale("fr_FR.UTF-8"), Some(Lang::Fr));
        assert_eq!(Lang::from_locale("de_DE@euro"), Some(Lang::De));
        assert_eq!(Lang::from_locale("it_IT"), Some(Lang::It));
        assert_eq!(Lang::from_locale("nl_BE.UTF-8"), Some(Lang::Nl));
        assert_eq!(Lang::from_locale("pl_PL.UTF-8"), Some(Lang::Pl));
        assert_eq!(Lang::from_locale("ja_JP:pt_BR:en_US"), Some(Lang::Pt));
        assert_eq!(Lang::from_locale("C.UTF-8"), None);
        assert_eq!(Lang::from_locale("POSIX"), None);
        assert_eq!(Lang::from_locale(""), None);
    }
}
