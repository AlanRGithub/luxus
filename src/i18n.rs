//! Multi-language localization for Luxus with automatic Linux OS locale detection.
//! Supported languages: Español, English, Português, Français, Deutsch, Italiano, Nederlands, Polski.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Es,
    En,
    Pt,
    Fr,
    De,
    It,
    Nl,
    Pl,
}

impl Lang {
    pub const ALL: [Lang; 8] = [
        Lang::Es,
        Lang::En,
        Lang::Pt,
        Lang::Fr,
        Lang::De,
        Lang::It,
        Lang::Nl,
        Lang::Pl,
    ];

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Es => "Español",
            Lang::En => "English",
            Lang::Pt => "Português",
            Lang::Fr => "Français",
            Lang::De => "Deutsch",
            Lang::It => "Italiano",
            Lang::Nl => "Nederlands",
            Lang::Pl => "Polski",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::Es => "es",
            Lang::En => "en",
            Lang::Pt => "pt",
            Lang::Fr => "fr",
            Lang::De => "de",
            Lang::It => "it",
            Lang::Nl => "nl",
            Lang::Pl => "pl",
        }
    }

    pub fn from_locale(raw: &str) -> Option<Lang> {
        let trimmed = raw.trim();
        if trimmed.is_empty() {
            return None;
        }
        for entry in trimmed.split(':') {
            let token = entry
                .trim()
                .split(&['.', '@', '_', '-'][..])
                .next()
                .unwrap_or("")
                .to_lowercase();
            match token.as_str() {
                "" | "c" | "posix" => continue,
                "es" => return Some(Lang::Es),
                "en" => return Some(Lang::En),
                "pt" => return Some(Lang::Pt),
                "fr" => return Some(Lang::Fr),
                "de" => return Some(Lang::De),
                "it" => return Some(Lang::It),
                "nl" => return Some(Lang::Nl),
                "pl" => return Some(Lang::Pl),
                _ => continue,
            }
        }
        None
    }
}

/// Detects the user's preferred language from POSIX locale variables (`LC_ALL`, `LC_MESSAGES`,
/// `LANGUAGE`, `LANG`), falling back to English.
pub fn detect_system_language() -> Lang {
    for var in ["LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"] {
        if let Ok(val) = std::env::var(var) {
            if let Some(lang) = Lang::from_locale(&val) {
                return lang;
            }
        }
    }
    Lang::En
}

